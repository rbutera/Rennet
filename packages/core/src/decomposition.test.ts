// ── Hunk-body content is never metadata (#310, core sibling pin) ─────────────

describe("parseFilePatch keeps `+++`/`---`-rendered body lines as hunk body (#310)", () => {
  // #310 named this core parser as a possible sibling of the adapters re-key bug.
  // Audit finding: it is NOT — metadata is read only in the preamble (`current ===
  // null`), hunk headers match the anchored HUNK_HEADER regex, and in-hunk lines are
  // classified by `charAt(0)` alone. This test PINS that: if a refactor ever flattened
  // core into the flat adapters shape (matching `+++ ` anywhere), the added line would
  // be dropped from the body and this reddens.
  it("an added line rendered `+++ b/other.txt` inside a hunk is carried as an addition", () => {
    const path = "changed.txt";
    const patch = filePatch(path, [{ lines: [" context", "+++ b/other.txt", "+ordinary add"] }]);
    const result = decompose(patchset([file(path, patch)]));
    // No metadata effect: every hunk keys to the real file, none to `other.txt`.
    expect(result.hunks.map((h) => h.filePath)).toEqual([path]);
    // The adversarial line is body content: an addition carrying `++ b/other.txt`
    // (its one-character `+` prefix stripped), alongside the ordinary add.
    expect(result.hunks[0]?.addedLines).toEqual(["++ b/other.txt", "ordinary add"]);
  });
});

// ── Chunking and the ≤400 budget ─────────────────────────────────────────────

describe("chunking", () => {
  it("keeps every substantive chunk within the ≤400 budget", () => {
    // Three 200-LOC hunks in one file: greedy-merge → 200+200=400, then 200.
    const hunk = (start: number): HunkSpec => ({
      newStart: start,
      lines: Array.from({ length: 200 }, (_, i) => `+line ${start}_${i}`),
    });
    const path = "src/big.ts";
    const result = decompose(
      patchset([file(path, filePatch(path, [hunk(1), hunk(201), hunk(401)]))]),
    );
    const substantive = result.chunks.filter((c) => c.kind === "substantive");
    for (const chunk of substantive)
      expect(chunk.changedLoc).toBeLessThanOrEqual(DEFAULT_MAX_CHUNK_LOC);
    expect(substantive.map((c) => c.changedLoc)).toEqual([400, 200]);
    assertTotality(result);
  });

  it("splits a 1000-line hunk into ≤400-LOC fragments and chunks", () => {
    const path = "src/huge.ts";
    const lines = Array.from({ length: 1000 }, (_, i) => `+row ${i}`);
    const result = decompose(patchset([file(path, filePatch(path, [{ newStart: 1, lines }]))]));

    const fragments = result.hunks.filter((h) => h.splitOf !== undefined);
    expect(fragments.length).toBe(3);
    expect(fragments.map((h) => h.splitOf?.index)).toEqual([0, 1, 2]);
    expect(fragments.every((h) => h.splitOf?.total === 3)).toBe(true);
    // Contiguity + LOC preservation: 400 + 400 + 200 = 1000.
    expect(fragments.map((h) => h.changedLoc)).toEqual([400, 400, 200]);
    expect(fragments.reduce((sum, h) => sum + h.changedLoc, 0)).toBe(1000);

    const substantive = result.chunks.filter((c) => c.kind === "substantive");
    expect(substantive.length).toBe(3);
    for (const chunk of substantive)
      expect(chunk.changedLoc).toBeLessThanOrEqual(DEFAULT_MAX_CHUNK_LOC);
    assertTotality(result);
  });

  it("groups by enclosing symbol when an extractor supplies one", () => {
    const path = "src/grouped.ts";
    const alpha: HunkSpec = { newStart: 1, lines: Array.from({ length: 250 }, (_, i) => `+a${i}`) };
    const beta: HunkSpec = {
      newStart: 300,
      lines: Array.from({ length: 250 }, (_, i) => `+b${i}`),
    };
    const extractor: SymbolExtractor = {
      enclosingSymbols(_path, hunks) {
        return hunks.map((_hunk, index) => (index === 0 ? "alpha" : "beta"));
      },
    };
    // 250 + 250 = 500 > 400, so the two symbol groups land in separate chunks.
    const result = decompose(patchset([file(path, filePatch(path, [alpha, beta]))]), {
      symbolExtractor: extractor,
    });
    const substantive = result.chunks.filter((c) => c.kind === "substantive");
    expect(substantive.map((c) => c.title)).toEqual([
      "src/grouped.ts · alpha",
      "src/grouped.ts · beta",
    ]);
    expect(result.classifications.filter((c) => c.enclosingSymbol === "alpha")).toHaveLength(1);
    expect(result.classifications.filter((c) => c.enclosingSymbol === "beta")).toHaveLength(1);
  });

  it("degrades to file-level grouping with the default extractor ('' symbols)", () => {
    const path = "src/plain.ts";
    const result = decompose(
      patchset([file(path, filePatch(path, [{ lines: ["+const a = 1;"] }]))]),
      { symbolExtractor: DEGRADED_SYMBOL_EXTRACTOR },
    );
    expect(result.classifications.every((c) => c.enclosingSymbol === "")).toBe(true);
    expect(result.chunks[0]?.title).toBe("src/plain.ts");
  });
});

// ── The dependency DAG and reading order ─────────────────────────────────────

describe("dependency DAG and reading order", () => {
  it("derives an enables edge from a relative import and orders the dependency first", () => {
    const model = file(
      "src/model.ts",
      filePatch("src/model.ts", [{ lines: ["+export interface Model {}"] }]),
    );
    const service = file(
      "src/service.ts",
      filePatch("src/service.ts", [
        { lines: ['+import { Model } from "./model";', "+export const s = 1;"] },
      ]),
    );
    const result = decompose(patchset([model, service]));

    const modelChunk = result.chunks.find((c) => c.filePaths[0] === "src/model.ts");
    const serviceChunk = result.chunks.find((c) => c.filePaths[0] === "src/service.ts");
    expect(result.edges).toContainEqual({
      from: modelChunk?.chunkId,
      to: serviceChunk?.chunkId,
      kind: "enables",
    });
    const modelPos = result.readingOrder.indexOf(modelChunk?.chunkId ?? "");
    const servicePos = result.readingOrder.indexOf(serviceChunk?.chunkId ?? "");
    expect(modelPos).toBeLessThan(servicePos);
    assertTopological(result);
  });

  it("breaks an import cycle so the stored edge set is a DAG", () => {
    const a = file(
      "src/a.ts",
      filePatch("src/a.ts", [{ lines: ['+import "./b";', "+export const a = 1;"] }]),
    );
    const b = file(
      "src/b.ts",
      filePatch("src/b.ts", [{ lines: ['+import "./a";', "+export const b = 1;"] }]),
    );
    const result = decompose(patchset([a, b]));

    // Exactly one of the two mutual edges survives; no back-edge closes the cycle.
    expect(result.edges.length).toBe(1);
    const pairs = new Set(result.edges.map((e) => `${e.from}->${e.to}`));
    for (const edge of result.edges) expect(pairs.has(`${edge.to}->${edge.from}`)).toBe(false);
    assertTopological(result);
  });

  it("is byte-stable across two runs on the same patchset", () => {
    const files = [
      file(
        "db/migrations/001_init.sql",
        filePatch("db/migrations/001_init.sql", [{ lines: ["+CREATE TABLE t (id int);"] }]),
      ),
      file("src/model.ts", filePatch("src/model.ts", [{ lines: ["+export interface Model {}"] }])),
      file(
        "src/service.ts",
        filePatch("src/service.ts", [{ lines: ['+import { Model } from "./model";'] }]),
      ),
      file("pnpm-lock.yaml", filePatch("pnpm-lock.yaml", [{ lines: ["+  a: 1"] }])),
    ];
    // The real guarantee: decompose the SAME patchset twice → byte-identical
    // output, no field normalization. (Two separate patchsets with different ids
    // would only test id-normalized equality, which is weaker.)
    const ps = patchset(files);
    const first = decompose(ps);
    const second = decompose(ps);
    expect(JSON.stringify(second)).toBe(JSON.stringify(first));
  });

  it("is independent of the order of patchset.files", () => {
    const files = [
      file(
        "db/migrations/001_init.sql",
        filePatch("db/migrations/001_init.sql", [{ lines: ["+CREATE TABLE t (id int);"] }]),
      ),
      file("src/model.ts", filePatch("src/model.ts", [{ lines: ["+export interface Model {}"] }])),
      file(
        "src/service.ts",
        filePatch("src/service.ts", [{ lines: ['+import { Model } from "./model";'] }]),
      ),
      file("pnpm-lock.yaml", filePatch("pnpm-lock.yaml", [{ lines: ["+  a: 1"] }])),
    ];
    // Same patchset (same id), files array in a DIFFERENT order. The floor's
    // defensive path-sort must make the output identical — proving the ordering
    // is a pure function of file content, not of arrival order.
    const base = patchset(files);
    const reordered = { ...base, files: [...base.files].reverse() };
    const inOrder = decompose(base);
    const shuffled = decompose(reordered);
    expect(JSON.stringify(shuffled)).toBe(JSON.stringify(inOrder));
  });
});

// ── The acceptance case: a real patchset renders offline, no model, no network ─

describe("the floor renders a real patchset with no harness and no network", () => {
  it("produces a complete decomposition from a realistic multi-file patchset", () => {
    const files = [
      file(
        "db/schema.sql",
        filePatch("db/schema.sql", [{ lines: ["+ALTER TABLE users ADD COLUMN age int;"] }]),
      ),
      file(
        "src/model.ts",
        filePatch("src/model.ts", [{ lines: ["+export interface User { age: number; }"] }]),
      ),
      file(
        "src/user-service.ts",
        filePatch("src/user-service.ts", [
          {
            lines: [
              '+import { User } from "./model";',
              "-const a = 1;",
              "+const a = 2;",
              " const keep = true;",
            ],
          },
        ]),
      ),
      file(
        "src/user-service.test.ts",
        filePatch("src/user-service.test.ts", [{ lines: ["+it('works', () => {});"] }]),
      ),
      file("src/style.ts", filePatch("src/style.ts", [{ lines: ["-  a();", "+    a();"] }])),
      file("pnpm-lock.yaml", filePatch("pnpm-lock.yaml", [{ lines: ["+  dep: 2.0.0"] }])),
    ];
    const result = decompose(patchset(files));

    // Every hunk classified; every substantive chunk within budget; totality holds.
    expect(result.classifications.length).toBe(result.hunks.length);
    for (const chunk of result.chunks.filter((c) => c.kind === "substantive")) {
      expect(chunk.changedLoc).toBeLessThanOrEqual(DEFAULT_MAX_CHUNK_LOC);
    }
    assertTotality(result);
    assertTopological(result);

    // The lockfile and the formatting-only change are mechanical (appendix);
    // schema/model/service/test are substantive.
    expect(classOf(result, "pnpm-lock.yaml")).toBe("lockfile");
    expect(classOf(result, "src/style.ts")).toBe("formatting-only");
    const substantiveFiles = new Set(
      result.chunks.filter((c) => c.kind === "substantive").map((c) => c.filePaths[0]),
    );
    expect(substantiveFiles).toContain("db/schema.sql");
    expect(substantiveFiles).toContain("src/model.ts");
    expect(substantiveFiles).toContain("src/user-service.ts");

    // The import edge orders the model before the service that imports it.
    const modelChunk = result.chunks.find((c) => c.filePaths[0] === "src/model.ts");
    const serviceChunk = result.chunks.find((c) => c.filePaths[0] === "src/user-service.ts");
    expect(result.edges).toContainEqual({
      from: modelChunk?.chunkId,
      to: serviceChunk?.chunkId,
      kind: "enables",
    });
  });
});
