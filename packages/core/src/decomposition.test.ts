// ── Fixture builders ─────────────────────────────────────────────────────────

interface HunkSpec {
  oldStart?: number;
  newStart?: number;
  /** Unified-diff body lines, each prefixed with `+`, `-`, or ` `. */
  lines: string[];
}

function filePatch(path: string, hunks: HunkSpec[]): string {
  const head = `diff --git a/${path} b/${path}\n--- a/${path}\n+++ b/${path}\n`;
  const body = hunks
    .map((hunk) => {
      const oldCount = hunk.lines.filter((l) => l[0] === "-" || l[0] === " ").length;
      const newCount = hunk.lines.filter((l) => l[0] === "+" || l[0] === " ").length;
      const header = `@@ -${hunk.oldStart ?? 1},${oldCount} +${hunk.newStart ?? 1},${newCount} @@`;
      return `${header}\n${hunk.lines.join("\n")}`;
    })
    .join("\n");
  return `${head}${body}\n`;
}

function file(path: string, patch: string, extra: Partial<PatchFile> = {}): PatchFile {
  return {
    path,
    status: "modified",
    additions: null,
    deletions: null,
    binary: false,
    patch,
    ...extra,
  };
}

let counter = 0;
function patchset(files: PatchFile[]): Patchset {
  counter += 1;
  return {
    id: `ps_${counter}`,
    createdAt: "2026-01-01T00:00:00.000Z",
    repository: {
      id: "repo",
      root: "/repo",
      commonDir: "/repo/.git",
      baseRef: "origin/main",
      baseOid: "0".repeat(40),
      headOid: "1".repeat(40),
    },
    files,
    rawDiff: "",
    byteLength: 0,
    truncated: false,
  };
}

/** Every hunk lands in exactly one chunk; residue is empty (totality, V100). */
function assertTotality(result: Decomposition): void {
  const placed = result.chunks.flatMap((c) => c.hunkIds);
  expect(new Set(placed).size).toBe(placed.length); // no duplication (V101)
  expect([...placed].sort()).toEqual(result.hunks.map((h) => h.id).sort());
  expect(result.residue).toEqual([]);
}

/** readingOrder covers every chunk once and respects every edge (V103). */
function assertTopological(result: Decomposition): void {
  expect([...result.readingOrder].sort()).toEqual(result.chunks.map((c) => c.chunkId).sort());
  const position = new Map(result.readingOrder.map((id, index) => [id, index]));
  for (const edge of result.edges) {
    expect(position.get(edge.from)).toBeLessThan(position.get(edge.to) ?? -1);
  }
}

function classOf(result: Decomposition, filePath: string): string | null {
  const hunk = result.hunks.find((h) => h.filePath === filePath);
  const classification = result.classifications.find((c) => c.hunkId === hunk?.id);
  return classification?.mechanical ?? null;
}

