/**
 * The shared, deterministic file-classification vocabulary: lockfile, vendored,
 * generated (by path or by header banner) and binary.
 *
 * Two consumers read the same tables, so the changeset view and the repo-wide
 * snapshot view classify the same path the same way:
 *  - `decomposition.ts` stamps a CHANGED file's hunks with a mechanical class, so
 *    a lockfile churn lands in the appendix instead of the review body;
 *  - `knowledge/partition.ts` classifies the WHOLE snapshot inventory, so a
 *    checked-in `dist/` is not batched for mapping (context-map rebuild, W2).
 *
 * They do not see the same evidence, and this module does not pretend they do.
 * Path classification is a pure function of the path and is identical either
 * side. The generated-BANNER check is not: the decomposer sees hunk bodies (so it
 * tracks line numbers through a diff) while the snapshot sees whole blob text, so
 * each owns its own walk over the shared {@link GENERATED_MARKERS} and
 * {@link GENERATED_HEADER_LINES}.
 *
 * Everything here is pure — no clock, no randomness, no IO — because the
 * snapshot-side result is content-addressed.
 */

